/*
    Перевірка числа (if/else):
    Дано число. Якщо воно більше 0 — вивести "Додатнє".
    Якщо менше 0 — "Від’ємне".
    Якщо дорівнює 0 — "Нуль".
*/

const num = 5;

if (num > 0) {
    console.log("додатнє");
}
else if (num < 0) {
    console.log("від'ємне");
}
else {
    console.log("нуль");
}